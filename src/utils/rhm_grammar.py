"""
Exact grammaticality and novelty tests for 2D Random Hierarchy Model samples.

A grid generated by some denoiser is a *valid* RHM sample iff it can be parsed:
iff there is an assignment of symbols to every node of the ``L``-level tree such
that each node's ``s x s`` block of children is one of that node's ``m``
production words. Because the model is a tree, this is decided exactly by one
bottom-up pass computing, for every node, the *set* of symbols that could have
produced the observed subtree below it:

    S_L(i, j) = { leaf token at (i, j) }
    S_l(i, j) = { a : exists a word w of a with rule[a, w, di, dj] in
                      S_{l+1}(s*i + di, s*j + dj) for every (di, dj) }

The grid is grammatical iff ``S_0`` (the root) is non-empty. The sets are carried
as ``v``-bit integer masks, so the whole pass is a handful of vectorized numpy
operations per level and runs on thousands of grids at once.

The intermediate sets are worth more than the final yes/no. ``parse_height``
reports how many levels compose successfully starting from the leaves, which
localizes *where* a denoiser breaks the grammar: a machine with a ``k x k``
window can only enforce rules whose children fit inside the window, so it should
parse correctly near the leaves and fail at the level where the block size
outgrows ``k``.
"""

from __future__ import annotations

import numpy as np

Array = np.ndarray


def feasible_symbol_masks(model, grids: Array) -> "list[Array]":
    """Bottom-up feasible-symbol sets for every node of every grid.

    Parameters
    ----------
    model : :class:`~src.utils.random_hierarchy.RandomHierarchyModel2D`.
    grids : (N, s**L, s**L) int array of leaf tokens.

    Returns
    -------
    masks : list of (N, s**l, s**l) uint64 arrays, l = 0..L. Bit ``a`` of
        ``masks[l][n, i, j]`` is set iff symbol ``a`` at that node could have
        generated the observed subtree beneath it. A zero entry means that
        subtree is unparseable.
    """
    v, s, L = model.v, model.s, model.L
    if v > 63:
        raise ValueError(f"v={v} exceeds the 63 symbols representable in a uint64 bitmask")
    grids = np.asarray(grids)
    expected = s ** L
    if grids.shape[-2:] != (expected, expected):
        raise ValueError(f"expected grids of shape (N, {expected}, {expected}), got {grids.shape}")

    masks = [None] * (L + 1)
    masks[L] = (np.uint64(1) << grids.astype(np.uint64))
    for l in range(L - 1, -1, -1):
        child = masks[l + 1]
        n, h, _ = child.shape
        nb = h // s
        # (n, nb, nb, s, s): regroup the child grid into this level's s x s blocks,
        # matching the (i*s + di, j*s + dj) layout that RandomHierarchyModel2D.sample uses.
        blocks = child.reshape(n, nb, s, nb, s).transpose(0, 1, 3, 2, 4)
        rule = model.rules[l]  # (v, m, s, s)
        out = np.zeros((n, nb, nb), dtype=np.uint64)
        for a in range(v):
            for wi in range(model.m):
                # A word fits iff every one of its s*s child symbols is feasible below.
                fits = np.ones((n, nb, nb), dtype=bool)
                for di in range(s):
                    for dj in range(s):
                        need = np.uint64(1) << np.uint64(rule[a, wi, di, dj])
                        fits &= (blocks[:, :, :, di, dj] & need) != 0
                        if not fits.any():
                            break
                    if not fits.any():
                        break
                out |= np.where(fits, np.uint64(1) << np.uint64(a), np.uint64(0))
        masks[l] = out
    return masks


def is_grammatical(model, grids: Array) -> Array:
    """(N,) bool array: does each grid parse all the way to a root symbol?"""
    return feasible_symbol_masks(model, grids)[0][:, 0, 0] != 0


def parse_height(model, grids: Array) -> Array:
    """(N,) int array: how many levels compose successfully, counting from the leaves.

    ``L`` means fully grammatical (the root parsed); ``L - 1`` means every
    ``s x s`` block of level-1 symbols parsed but the root rule was violated, and
    so on down to 0, which means some lowest-level ``s x s`` leaf block is not a
    word of any symbol.
    """
    masks = feasible_symbol_masks(model, grids)
    n = grids.shape[0]
    height = np.zeros(n, dtype=np.int64)
    for l in range(model.L, -1, -1):
        ok = (masks[l] != 0).reshape(n, -1).all(axis=1)
        height = np.where(ok, model.L - l, height)
    return height


def valid_block_fraction(model, grids: Array, level: int) -> float:
    """Fraction of level-``level`` nodes whose own subtree parses, over all grids.

    A softer, higher-resolution companion to :func:`is_grammatical`: a machine
    that violates one rule in one corner scores the same 0 as one that violates
    every rule, and this separates them.
    """
    return float((feasible_symbol_masks(model, grids)[level] != 0).mean())


def _rows_as_keys(grids: Array) -> Array:
    """Hashable 1-D view of each grid, for exact set membership."""
    g = np.ascontiguousarray(np.asarray(grids, dtype=np.int8))
    return g.reshape(g.shape[0], -1).view([('', np.int8)] * (g.shape[1] * g.shape[2])).ravel()


def is_novel(train_grids: Array, grids: Array) -> Array:
    """(N,) bool array: is each grid absent from the training set, exactly?

    Exact grid equality, which is the right notion here: unlike pixels, tokens
    have no metric, so "close to a training sample" is not meaningful and a
    single differing token already makes a different sentence of the grammar.
    """
    train = set(_rows_as_keys(train_grids).tolist())
    return np.array([key not in train for key in _rows_as_keys(grids).tolist()], dtype=bool)


def evaluate_samples(model, train_grids: Array, grids: Array) -> dict:
    """Both success criteria at once, plus the diagnostics that explain them.

    Returns a dict with ``grammatical``, ``novel`` and ``success`` (the fraction
    satisfying both -- hshunt's criterion), the mean ``parse_height``, and the
    per-level fraction of parseable subtrees.
    """
    gram = is_grammatical(model, grids)
    novel = is_novel(train_grids, grids)
    masks = feasible_symbol_masks(model, grids)
    n = grids.shape[0]
    return {
        'n_samples': int(n),
        'grammatical': float(gram.mean()),
        'novel': float(novel.mean()),
        'success': float((gram & novel).mean()),
        'parse_height_mean': float(parse_height(model, grids).mean()),
        'level_parse_fraction': [float((masks[l] != 0).mean()) for l in range(model.L + 1)],
        'n_distinct': int(len(set(_rows_as_keys(grids).tolist()))),
    }
